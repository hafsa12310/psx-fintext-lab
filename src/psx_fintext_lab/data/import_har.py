"""Import PSX announcement tables from HAR files recorded in Chrome DevTools.

The PSX portal requires a per-request token generated by its own JavaScript, so we don't
scrape it with a script. Instead, browse the announcements normally with DevTools open,
export the Network log as a HAR file into data/raw/har/, and run:  uv run import-psx
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path
from urllib.parse import parse_qs

import pandas as pd

from psx_fintext_lab.data.common import RAW_DIR, load_data_config
from psx_fintext_lab.data.psx_html import COMBINED_PATH, parse_html_table

HAR_DIR = RAW_DIR / "har"


def form_fields(entry: dict) -> dict[str, str]:
    """The form fields the browser POSTed, e.g. {"type": "C", "offset": "50", ...}."""
    text = entry["request"].get("postData", {}).get("text", "")
    return {key: values[0] for key, values in parse_qs(text, keep_blank_values=True).items()}


def response_html(entry: dict) -> str:
    """The response body. Chrome sometimes stores it base64-encoded."""
    content = entry["response"].get("content", {})
    text = content.get("text", "")
    if content.get("encoding") == "base64":
        text = base64.b64decode(text).decode("utf-8", errors="replace")
    return text


def tables_from_har(path: Path, request_url: str, wanted_type: str) -> list[pd.DataFrame]:
    """Every announcements table in one HAR file, for the wanted announcement type only."""
    entries = json.loads(path.read_text(encoding="utf-8"))["log"]["entries"]
    frames = []
    for entry in entries:
        request = entry["request"]
        if request["method"] != "POST" or not request["url"].startswith(request_url):
            continue
        if entry["response"]["status"] != 200:
            continue
        if form_fields(entry).get("type") != wanted_type:
            continue  # e.g. skip PSX Notices if you clicked through those too
        df = parse_html_table(response_html(entry))
        if not df.empty:
            frames.append(df)
    return frames


def main() -> None:
    argparse.ArgumentParser(description="Import PSX announcements from HAR files").parse_args()
    cfg = load_data_config()["psx"]
    paths = sorted(HAR_DIR.glob("*.har"))
    if not paths:
        raise SystemExit(f"No .har files in {HAR_DIR}. Export one from Chrome DevTools first.")

    frames = []
    for path in paths:
        found = tables_from_har(path, cfg["request_url"], cfg["form"]["type"])
        print(f"{path.name}: {len(found)} pages, {sum(len(f) for f in found)} rows")
        frames.extend(found)
    if not frames:
        raise SystemExit("No announcement tables found. Check the type value in the config.")

    df = pd.concat(frames, ignore_index=True)
    before = len(df)
    df = df.drop_duplicates()  # the same page recorded twice
    print(f"Removed {before - len(df)} duplicate rows from repeated pages")
    print("Columns:", df.columns.tolist())

    COMBINED_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(COMBINED_PATH, index=False)
    print(f"Saved {len(df)} rows to {COMBINED_PATH}")


if __name__ == "__main__":
    main()
